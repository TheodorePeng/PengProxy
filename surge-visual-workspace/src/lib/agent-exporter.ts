import { ProfileDiff } from '@/types/surge';

/**
 * Generates an actionable Change Plan prompt for local AI agents (e.g. surge-operator-peng).
 */
export function generateAgentChangePlan(diff: ProfileDiff, filename: string = 'Surge-Peng.conf'): string {
  const timestamp = new Date().toISOString();

  return `### Surge Configuration Change Plan (Generated by Surge Visual Workspace)
**Target Profile:** \`${filename}\`
**Generated At:** \`${timestamp}\`
**Status:** Ready to Apply

#### 1. Operations Required
1. **Safety Backup**: Create a backup of the current active profile before any mutation:
   \`cp "/Users/peng/Library/Application Support/Surge/Profiles/${filename}" "/Users/peng/Library/Application Support/Surge/Profiles/${filename}.bak-${Date.now()}"\`
2. **Apply Modified Content**: Update the profile with the verified content.
3. **Validate & Reload**: Inspect profile syntax and reload Surge config using Surge CLI or HTTP API.

#### 2. Detailed Line Diff
\`\`\`diff
${diff.diffLines
  .filter((l) => l.type !== 'unchanged')
  .map((l) => (l.type === 'add' ? `+ ${l.value}` : `- ${l.value}`))
  .join('\n')}
\`\`\`

#### 3. Agent Execution Instructions
Please read the above diff and apply these specific changes to \`/Users/peng/Library/Application Support/Surge/Profiles/${filename}\` safely. Ensure no unrelated comments or sections are modified.
`;
}
